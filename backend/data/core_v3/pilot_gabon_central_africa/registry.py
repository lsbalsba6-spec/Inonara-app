def _name_by_value(entity, value):
    return next(n for n in entity["names"] if n["value"] == value)


def _status_by_value(entity, value):
    return next(s for s in entity["statuses"] if s["value"] == value)


def _relation_by_type_and_entities(rel_type, from_id, to_id):
    return next(r for r in relations if r["relationType"] == rel_type and r["fromEntityId"] == from_id and r["toEntityId"] == to_id)


