const I18nCtx = createContext({ lang: "en", t: (k) => k, setLang: () => {} });

export const I18nProvider = ({ children }) => {
  const [lang, setLang] = useState(() => localStorage.getItem("afroatlas.lang") || "en");
  useEffect(() => { localStorage.setItem("afroatlas.lang", lang); document.documentElement.lang = lang; }, [lang]);
  const t = (key) => dict[lang][key] || dict.en[key] || key;
  return <I18nCtx.Provider value={{ lang, t, setLang }}>{children}</I18nCtx.Provider>;
};

export const useI18n = () => useContext(I18nCtx);
